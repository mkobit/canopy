import { describe, expect, test } from 'bun:test';
import fs from 'node:fs';
import path from 'node:path';
import { CANOPY_WIT_SPECIFICATION } from '../src';

describe('Plugin host schema baseline', () => {
  test('the inline WIT baseline and waiver manifest exist and match the current export', () => {
    const baselinesDirectory = path.resolve(__dirname, '../schema-baselines');
    const witPath = path.join(baselinesDirectory, 'plugin.wit');
    const schemaPath = path.join(baselinesDirectory, 'approved-breaking-changes.schema.json');
    const waiverPath = path.join(baselinesDirectory, 'approved-breaking-changes.json');

    expect(fs.existsSync(witPath)).toBe(true);
    expect(fs.existsSync(schemaPath)).toBe(true);
    expect(fs.existsSync(waiverPath)).toBe(true);

    const witContent = fs.readFileSync(witPath, 'utf8');
    expect(witContent).toContain('AUTOGENERATED BASELINE FILE - DO NOT EDIT MANUALLY');
    expect(witContent).toContain('package canopy:graph-api@0.1.0;');
    expect(witContent).toBe(
      `/* AUTOGENERATED BASELINE FILE - DO NOT EDIT MANUALLY */\n${CANOPY_WIT_SPECIFICATION}`,
    );

    const waiverContent = JSON.parse(fs.readFileSync(waiverPath, 'utf8')) as {
      readonly waivers: readonly unknown[];
    };
    expect(waiverContent.waivers).toEqual([]);
  });
});
