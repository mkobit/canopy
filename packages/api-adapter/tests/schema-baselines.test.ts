import { describe, expect, test } from 'bun:test';
import fs from 'node:fs';
import path from 'node:path';
import { JSON_RPC_IPC_SPECIFICATION } from '../src';

describe('Schema Baseline Snapshots', () => {
  const baselinesDirectory = path.resolve(__dirname, '../schema-baselines');

  test('baseline snapshot files exist and match current exports', () => {
    const ipcPath = path.join(baselinesDirectory, 'ipc-openrpc.json');
    const schemaPath = path.join(baselinesDirectory, 'approved-breaking-changes.schema.json');
    const waiverPath = path.join(baselinesDirectory, 'approved-breaking-changes.json');

    expect(fs.existsSync(ipcPath)).toBe(true);
    expect(fs.existsSync(schemaPath)).toBe(true);
    expect(fs.existsSync(waiverPath)).toBe(true);

    const ipcContent = fs.readFileSync(ipcPath, 'utf8');
    expect(ipcContent).toContain('AUTOGENERATED BASELINE FILE - DO NOT EDIT MANUALLY');
    expect(ipcContent).toContain('canopy.v1.query.getNode');
    expect(ipcContent).toContain(JSON_RPC_IPC_SPECIFICATION.trim());

    const waiverContent = JSON.parse(fs.readFileSync(waiverPath, 'utf8')) as {
      readonly waivers: readonly unknown[];
    };
    expect(waiverContent.waivers).toEqual([]);
  });
});
